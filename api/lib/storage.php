<?php
declare(strict_types=1);

require_once __DIR__ . '/config.php';
require_once __DIR__ . '/response.php';

/**
 * Uploaded-file storage on a host with FTP but no shell.
 *
 * Three rules shape everything here:
 *
 * 1. A stored path is never built from a user-supplied name. The original
 *    filename is kept in the database for display only; on disk a file is a
 *    server-generated random key. A name like "../../config.php" therefore has
 *    nowhere to go — it is data, not a path.
 * 2. Nothing under the storage root is ever web-readable. The directory gets a
 *    deny-all .htaccess the moment it is created, api/.htaccess 404s the whole
 *    path, and files are only ever served back through a PHP route that checks
 *    ownership first.
 * 3. The root is configurable but must not need configuring: the default sits
 *    beside the API so a deploy to a fresh server works without editing
 *    config.php, which only exists on the server and cannot be deployed.
 */
final class Storage
{
    /** Written into the storage root so a misconfigured vhost still cannot serve it. */
    private const DENY_HTACCESS = <<<'TXT'
    # Uploaded source material. Never web-readable: files are served only by
    # /v1/sources/{id}/file, which checks ownership first.
    Require all denied
    Options -Indexes
    TXT;

    public static function root(): string
    {
        $configured = (string) Config::get('uploads.path', '');
        $root = $configured !== '' ? $configured : dirname(__DIR__) . '/storage';

        return rtrim($root, '/\\');
    }

    /**
     * Writes an uploaded file and returns its storage key.
     *
     * The key is relative to the root and scoped by user, so one user's files
     * are never interleaved with another's on disk — which makes a stray
     * directory listing during support far less revealing.
     */
    public static function put(int $userId, string $temporaryPath, string $extension): string
    {
        $extension = self::normalizeExtension($extension);
        $directory = self::root() . '/' . $userId;

        self::ensureDirectory(self::root());
        self::ensureDirectory($directory);

        // 16 bytes of randomness: the key is not a secret (the route checks
        // ownership) but an unguessable name is one more thing in the way.
        $key  = $userId . '/' . bin2hex(random_bytes(16)) . ($extension === '' ? '' : '.' . $extension);
        $path = self::root() . '/' . $key;

        // move_uploaded_file refuses anything that did not arrive as an upload,
        // so a crafted path in $_FILES cannot make this copy an arbitrary file.
        if (!move_uploaded_file($temporaryPath, $path)) {
            throw new RuntimeException('could not store the uploaded file');
        }

        chmod($path, 0640);

        return $key;
    }

    /**
     * Writes server-generated bytes at a caller-chosen key.
     *
     * Separate from put(): that one moves an *upload*, and deliberately uses
     * move_uploaded_file so a crafted path in $_FILES cannot make it copy an
     * arbitrary file. This one never touches request data — the key is derived
     * from content the server already has, which is what makes a cache key
     * usable as a filename.
     */
    public static function write(string $key, string $bytes): void
    {
        $path = self::pathFor($key);

        self::ensureDirectory(self::root());
        self::ensureDirectory(dirname($path));

        // Written to a neighbouring temp name and moved into place, so a
        // concurrent reader never sees a half-written file and treat it as a
        // complete cache entry.
        $temp = $path . '.' . bin2hex(random_bytes(4)) . '.part';

        if (file_put_contents($temp, $bytes) === false || !rename($temp, $path)) {
            @unlink($temp);
            throw new RuntimeException('could not write to storage');
        }

        chmod($path, 0640);
    }

    public static function pathFor(string $key): string
    {
        return self::root() . '/' . self::assertSafeKey($key);
    }

    public static function exists(string $key): bool
    {
        return is_file(self::pathFor($key));
    }

    public static function delete(string $key): void
    {
        $path = self::pathFor($key);
        if (is_file($path)) {
            @unlink($path);
        }
    }

    /**
     * Streams a stored file to the client in chunks.
     *
     * readfile() would load a 25MB recording into memory in one go and trip the
     * PHP memory limit on shared hosting; this holds 64KB at a time instead.
     */
    public static function stream(string $key): void
    {
        $handle = fopen(self::pathFor($key), 'rb');
        if ($handle === false) {
            throw new RuntimeException('could not open the stored file');
        }

        while (!feof($handle)) {
            echo fread($handle, 65536);
            flush();
        }

        fclose($handle);
    }

    /** True when the storage root exists and PHP can write to it. */
    public static function isWritable(): bool
    {
        try {
            self::ensureDirectory(self::root());
        } catch (RuntimeException) {
            return false;
        }

        return is_writable(self::root());
    }

    // ------------------------------------------------------------ internals --

    private static function ensureDirectory(string $path): void
    {
        if (!is_dir($path) && !@mkdir($path, 0750, true) && !is_dir($path)) {
            throw new RuntimeException("could not create the storage directory: {$path}");
        }

        $htaccess = $path . '/.htaccess';
        if ($path === self::root() && !is_file($htaccess)) {
            @file_put_contents($htaccess, self::DENY_HTACCESS . "\n");
        }
    }

    /**
     * A key only ever comes from our own database, but it is still checked
     * before it reaches the filesystem — a bug or a bad migration must not
     * become a path traversal.
     */
    private static function assertSafeKey(string $key): string
    {
        // Two shapes, both anchored and both user-scoped:
        //   12/<32 hex>.pdf       an upload
        //   tts/12/<64 hex>.mp3   a cached synthesis, in its own namespace
        // No dots, no slashes beyond these, so "..", absolute paths and the
        // rest cannot be expressed at all.
        if (!preg_match('#^(?:[a-z]{1,8}/)?\d+/[a-f0-9]{32,64}(\.[a-z0-9]{1,8})?$#', $key)) {
            throw new RuntimeException('refusing to use a malformed storage key');
        }

        return $key;
    }

    private static function normalizeExtension(string $extension): string
    {
        $extension = strtolower(ltrim($extension, '.'));

        return preg_match('/^[a-z0-9]{1,8}$/', $extension) === 1 ? $extension : 'bin';
    }
}
